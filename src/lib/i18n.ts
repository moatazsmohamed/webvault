export type DictKey = keyof typeof DICT;

export function translate(locale: Locale, key: DictKey, vars?: Record<string, string | number>): string {
  const entry = DICT[key];
  if (!entry) return String(key);
  let text = entry[locale] ?? entry.en;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  }
  return text;
}

export const dirOf = (locale: Locale): 'rtl' | 'ltr' => (locale === 'ar' ? 'rtl' : 'ltr');

/** Maps an audit action like `room.create` onto its dictionary entry, if one exists. */
export function activityLabel(locale: Locale, action: string): string {
  const key = `act_${action.replace(/[.-]/g, '_')}` as DictKey;
  return key in DICT ? translate(locale, key) : action;
}
